"""Prepaid credit customers hold with providers, the payments that fund it, and providers' gateway connections.

Money never passes through AgentMesh: a customer pays a provider directly (through the provider's own payment gateway
account, or by a method the provider confirms by hand). Once a payment is verified, the customer holds that much
credit with that provider; usage on the provider's priced machines draws it down, and priced service needs credit.
"""

import enum
import uuid
from datetime import datetime

from pydantic import Field

from app.core.timeutil import utcnow
from app.documents.base import ZERO, Doc, Money, index, unique


class CreditBalance(Doc):
    """What one customer has left with one provider, in one currency. Changed only together with a CreditEntry."""

    customer_id: uuid.UUID
    provider_id: uuid.UUID
    currency: str
    balance: Money = ZERO
    updated_at: datetime = Field(default_factory=utcnow)

    class Settings(Doc.Settings):
        name = "credit_balances"
        indexes = [
            unique("customer_id", "provider_id", "currency", name="uq_credit_balances_owner"),
            index("provider_id"),
        ]


class CreditEntry(Doc):
    """Append-only record of every change to a balance. The unique key makes each change happen once."""

    customer_id: uuid.UUID
    provider_id: uuid.UUID
    currency: str
    amount: Money  # positive: verified payment or adjustment; negative: usage
    kind: str  # payment | usage | reversal
    key: str  # idempotency key, e.g. payment:<id> or estimate:<id>
    payment_id: uuid.UUID | None = None
    estimate_id: uuid.UUID | None = None
    deployment_id: uuid.UUID | None = None
    created_at: datetime = Field(default_factory=utcnow)

    class Settings(Doc.Settings):
        name = "credit_entries"
        indexes = [unique("key", name="uq_credit_entries_key"), index("customer_id", "provider_id", "created_at")]


class PaymentMethod(str, enum.Enum):  # noqa: UP042
    GATEWAY = "gateway"  # verified automatically with the provider's own gateway account
    MANUAL = "manual"  # confirmed by the provider in their dashboard


class PaymentState(str, enum.Enum):  # noqa: UP042
    PENDING = "PENDING"  # started; not verified yet
    VERIFIED = "VERIFIED"  # verified and credited exactly once
    FAILED = "FAILED"  # the gateway reports it failed or abandoned, or it expired unverified
    REJECTED = "REJECTED"  # the provider says it did not receive it
    REVIEW = "REVIEW"  # the gateway reports success but amount or currency differ: never credited automatically


class CreditPayment(Doc):
    customer_id: uuid.UUID
    provider_id: uuid.UUID
    method: str
    gateway: str | None = None  # paystack | flutterwave | stripe
    amount: Money
    currency: str
    reference: str  # generated by AgentMesh (gateway) or the customer's transfer reference (manual)
    gateway_ref: str | None = None  # e.g. Stripe checkout session id
    checkout_url: str | None = None
    state: str = PaymentState.PENDING.value
    gateway_status: str | None = None
    note: str | None = None
    decided_by: uuid.UUID | None = None
    reason: str | None = None
    verified_at: datetime | None = None
    last_checked_at: datetime | None = None
    created_at: datetime = Field(default_factory=utcnow)

    class Settings(Doc.Settings):
        name = "credit_payments"
        indexes = [
            unique("provider_id", "method", "reference", name="uq_credit_payments_reference"),
            index("customer_id", "created_at"),
            index("provider_id", "state", "created_at"),
            index("state", "method", "created_at"),
        ]


class ProviderGateway(Doc):
    """A provider's own payment gateway account. The secret key is encrypted at rest and never returned."""

    provider_id: uuid.UUID
    gateway: str  # paystack | flutterwave | stripe
    secret_encrypted: str
    key_hint: str  # last 4 characters, to recognise the key
    mode: str  # test | live
    verified_at: datetime | None = None
    created_at: datetime = Field(default_factory=utcnow)
    updated_at: datetime = Field(default_factory=utcnow)

    class Settings(Doc.Settings):
        name = "provider_gateways"
        indexes = [unique("provider_id", "gateway", name="uq_provider_gateways")]
